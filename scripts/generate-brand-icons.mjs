/**
 * Extracts the brand glyphs the site uses into lib/brand-icons.ts so the app
 * ships no icon dependency at runtime.
 *
 *   npm i --no-save simple-icons @iconify-json/ri @iconify-json/mdi
 *   node scripts/generate-brand-icons.mjs
 *
 * simple-icons dropped LinkedIn, AWS, OpenAI and Grok over trademark policy,
 * so those four come from Remix Icon / Material Design Icons instead and carry
 * a hand-set brand colour. `dark` overrides exist for brands whose real colour
 * is near-black and would vanish on the dark theme.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const si = require("simple-icons");
const ri = require("@iconify-json/ri/icons.json");
const mdi = require("@iconify-json/mdi/icons.json");

const fromSimple = (slug, over = {}) => {
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons is missing ${slug}`);
  return {
    title: icon.title,
    hex: `#${icon.hex}`,
    body: `<path d="${icon.path}"/>`,
    ...over,
  };
};

const fromSet = (set, name, meta) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`icon set is missing ${name}`);
  return { body: icon.body, ...meta };
};

const ICONS = {
  // Social — hover colours are the hand-picked brand values from the brief.
  linkedin: fromSet(ri, "linkedin-fill", { title: "LinkedIn", hex: "#0A66C2" }),
  github: fromSimple("github", { hex: "#8957E5" }),
  stackoverflow: fromSimple("stackoverflow", { hex: "#F48024" }),
  dart: fromSimple("dart", { title: "pub.dev", hex: "#13B9FD" }),
  upwork: fromSimple("upwork", { hex: "#14A800" }),
  fiverr: fromSimple("fiverr", { hex: "#1DBF73" }),
  x: fromSimple("x", { hex: "#1D9BF0" }),
  instagram: fromSimple("instagram", { hex: "#E4405F" }),
  facebook: fromSimple("facebook", { hex: "#1877F2" }),
  // Tools
  flutter: fromSimple("flutter"),
  ionic: fromSimple("ionic"),
  react: fromSimple("react"),
  angular: fromSimple("angular", { hex: "#DD0031" }),
  node: fromSimple("nodedotjs"),
  mongodb: fromSimple("mongodb"),
  python: fromSimple("python"),
  xcode: fromSimple("xcode"),
  figma: fromSimple("figma"),
  clickup: fromSimple("clickup"),
  trello: fromSimple("trello"),
  notion: fromSimple("notion", { dark: "#FFFFFF" }),
  digitalocean: fromSimple("digitalocean"),
  aws: fromSet(mdi, "aws", { title: "AWS", hex: "#FF9900" }),
  langchain: fromSimple("langchain", { hex: "#1C3C3C", dark: "#7FC8FF" }),
  claude: fromSimple("claude"),
  chatgpt: fromSet(ri, "openai-fill", { title: "ChatGPT", hex: "#10A37F" }),
  grok: fromSet(ri, "grok-ai-fill", {
    title: "Grok",
    hex: "#000000",
    dark: "#FFFFFF",
  }),

  // Non-brand marks used alongside them
  qa: fromSet(mdi, "bug-check-outline", { title: "Manual QA", hex: "#16A34A" }),
  seo: fromSet(mdi, "chart-line", { title: "SEO", hex: "#2563EB" }),
  googleplay: fromSimple("googleplay", { hex: "#01875F" }),
  web: fromSet(mdi, "web", { title: "Web", hex: "#0EA5E9" }),
};

const entries = Object.entries(ICONS)
  .map(
    ([slug, { title, hex, dark, body }]) =>
      `  ${slug}: {\n` +
      `    title: ${JSON.stringify(title)},\n` +
      `    hex: ${JSON.stringify(hex)},\n` +
      (dark ? `    dark: ${JSON.stringify(dark)},\n` : "") +
      `    body: ${JSON.stringify(body)},\n` +
      `  },`,
  )
  .join("\n");

const out = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Every glyph is a 24×24 monochrome silhouette drawn in currentColor; \`hex\`
// is the brand colour used on hover, and \`dark\` overrides it on the dark
// theme for brands whose real colour is near-black.

export type BrandIcon = {
  title: string;
  hex: string;
  dark?: string;
  body: string;
};

export const brandIcons = {
${entries}
} as const satisfies Record<string, BrandIcon>;

export type BrandSlug = keyof typeof brandIcons;
`;

writeFileSync(new URL("../lib/brand-icons.ts", import.meta.url), out);
console.log(`wrote ${Object.keys(ICONS).length} icons`);
